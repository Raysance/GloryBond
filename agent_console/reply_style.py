"""Shared expression policy for the factual draft and presentation stage."""

import re


def default_assistant_instruction():
    return (
        "未扮演角色时，默认立场鲜明、语气坚定，有主见，直接给出判断和理由。"
        "发现错误直接指出，面对无依据的归因或不合理要求明确反驳，不迎合、讨好或一味附和。"
        "用简洁、有分寸的措辞说清问题，不用辱骂、人身攻击或居高临下的训话。"
        "判断力度与依据相符，未知信息和实际执行状态照实说明。"
        "用户当次表达要求及已保存的表达偏好可以调整默认语气。"
    )


def reply_style_instruction():
    return (
        "回复表达约定适用于详细正文、群聊短版及阶段性回答，优先于角色样例和旧的表达习惯。"
        "直接回应问题，先给有依据的结论，再按需要给事实、数据和做法；语气自然、平等。"
        "省去防御式开场、预先反驳和说教，不使用‘只能’‘不是……而是……’‘不能表明’"
        "‘不能证明’‘没有详细的证据’‘先说清楚’‘先讲清楚’等口吻，也不换成相近的免责声明。"
        "需要交代范围时直接写数据来源、覆盖时间和样本；缺信息时具体说缺哪一项，"
        "失败时直接说执行状态及下一步，不泛泛强调证据不足或反复否定用户的推断。"
        "例如写‘统计覆盖本群最近20条消息’，写‘这8场拿下5胜，胜率62.5%’，"
        "写‘还缺对局日期，补上日期后可以继续查询’。"
        "事实准确性、必要的不确定性和实际执行结果照实保留；语气调整不增加确定性或省略重要条件。"
        "用户要求核对的原文、引用、代码、标题和接口原始报错保持原样，自己的解释遵守本约定。"
    )


def validate_reply_style(text):
    """Repair generated narration without replacing words inside evidence or quotes."""
    narration = re.sub(r'“[^”]*”|「[^」]*」|‘[^’]*’|"[^"\n]*"|`[^`]*`', "", text)
    if re.search(r"只能|不是[^。！？\n]{0,120}而是|不能(?:表明|证明)|"
                 r"没有(?:详细|足够|充分)的?(?:证据|依据)|先(?:说|讲)清楚", narration):
        raise ValueError("将防御性表述改为直接陈述事实、数据范围或具体缺项，保留原有结论及条件")
